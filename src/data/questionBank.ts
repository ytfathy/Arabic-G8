export function getAllQuestions(): Question[] {
  return [...RAW_QUESTIONS];
}

export function getQuestionsByWeek(week: number): Question[] {
  return RAW_QUESTIONS.filter(q => q.week === week);
}

export function getQuestionsBySkill(skill: SkillCategory): Question[] {
  return RAW_QUESTIONS.filter(q => q.skill === skill);
}

export function getQuestionsByLesson(lessonName: string): Question[] {
  return RAW_QUESTIONS.filter(q => q.lessonName === lessonName);
}

export function getDistinctLessons(): LessonSummary[] {
  const map = new Map<string, LessonSummary>();
  
  for (const q of RAW_QUESTIONS) {
    if (!map.has(q.lessonName)) {
      map.set(q.lessonName, {
        id: q.lessonName.replace(/\s+/g, '_'),
        name: q.lessonName,
        skill: q.skill,
        skillLabel: q.skillLabel,
        unit: q.unit,
        unitTitle: q.unitTitle,
        week: q.week,
        questionCount: 1
      });
    } else {
      const item = map.get(q.lessonName)!;
      item.questionCount += 1;
    }
  }

  return Array.from(map.values());
}
