export function resolvePassageForQuestion(q: Question): { passageTitle?: string; passageText?: string } {
  if (q.passageText && q.passageTitle) {
    return { passageTitle: q.passageTitle, passageText: q.passageText };
  }

  const lookup = `${q.passageTitle || ''} ${q.lessonName || ''}`;

  let matched: { title: string; text: string } | undefined;

  if (lookup.includes('آمنة') || lookup.includes('دهشان')) matched = PASSAGES.amna_dahshan;
  else if (lookup.includes('العبور') || lookup.includes('أكتوبر')) matched = PASSAGES.al_uboor;
  else if (lookup.includes('مبروك') || lookup.includes('الواجب') || lookup.includes('صقور')) matched = PASSAGES.mohamed_mabrouk;
  else if (lookup.includes('خاطري')) matched = PASSAGES.masr_fi_khatiri;
  else if (lookup.includes('وديعة')) matched = PASSAGES.aqdam_wadeea;
  else if (lookup.includes('غد')) matched = PASSAGES.min_ajl_ghad;
  else if (lookup.includes('الخارجة') || lookup.includes('البيئة')) matched = PASSAGES.madinat_al_kharga;
  else if (lookup.includes('ريفنا')) matched = PASSAGES.rifuna_al_masry;
  else if (lookup.includes('إنسان') || lookup.includes('ظل')) matched = PASSAGES.insan_am_zill;
  else if (lookup.includes('الخوارزمي')) matched = PASSAGES.al_khawarizmi;
  else if (lookup.includes('القراءة حياة')) matched = PASSAGES.al_qiraa_hayah;
  else if (lookup.includes('الكد') || lookup.includes('المعالي')) matched = PASSAGES.al_kadd_sabil_al_maali;
  else if (lookup.includes('حماة') || lookup.includes('بطولات')) matched = PASSAGES.homat_al_watan;
  else if (lookup.includes('أخلاقيات') || lookup.includes('الذكاء')) matched = PASSAGES.akhlaqiyat_al_ilm;

  if (matched) {
    return {
      passageTitle: q.passageTitle || matched.title,
      passageText: q.passageText || matched.text
    };
  }

  return {
    passageTitle: q.passageTitle,
    passageText: q.passageText
  };
}

