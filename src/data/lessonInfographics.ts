  for (const mapping of KEYWORD_MAP) {
    if (mapping.keywords.some(k => target.includes(k))) {
      const found = LESSON_INFOGRAPHICS.find(info => info.id === mapping.id);
      if (found) return found;
    }
  }

  // 4. Fallback: match by skill if known
  return LESSON_INFOGRAPHICS[0];
